// ── Nepali numeral ─────────────────────────────────────────────────────────
const NP_DIGITS = ['०','१','२','३','४','५','६','७','८','९'];

/** Converts a JS number to a Nepali numeral string. */
export function toNepaliNum(n: number): string {
  return String(n).split('').map(c => NP_DIGITS[+c] ?? c).join('');
}

// ── Core conversion helpers ────────────────────────────────────────────────

/** Returns the number of days between two Date objects (d2 - d1), ignoring time. */
function daysBetween(d1: Date, d2: Date): number {
  const t1 = Date.UTC(d1.getFullYear(), d1.getMonth(), d1.getDate());
  const t2 = Date.UTC(d2.getFullYear(), d2.getMonth(), d2.getDate());
  return Math.round((t2 - t1) / 86_400_000);
}

/**
 * Converts a Gregorian date to Bikram Sambat.
 * @throws if the date is before 14 April 1943 or after 2090 BS.
 */
export function adToBs(adDate: Date): BsDate {
  let diff = daysBetween(EPOCH_AD, adDate);
  if (diff < 0) throw new RangeError('adToBs: date is before epoch (14 Apr 1943)');

  let year = EPOCH_BS_YEAR;

  // Consume whole BS years
  while (true) {
    const yearDays = BS_DATA[year]?.reduce((a, b) => a + b, 0);
    if (yearDays === undefined) throw new RangeError(`adToBs: year ${year} not in lookup table`);
    if (diff < yearDays) break;
    diff -= yearDays;
    year++;
  }

  // Consume whole BS months
  let month = 1;
  for (let m = 0; m < 12; m++) {
    const md = BS_DATA[year][m];
    if (diff < md) { month = m + 1; break; }
    diff -= md;
  }

  return { year, month, day: diff + 1 };
}

/**
 * Converts a Bikram Sambat date to Gregorian.
 */
export function bsToAd(year: number, month: number, day: number): Date {
  let totalDays = 0;

  // Add complete BS years from epoch year to year-1
  for (let y = EPOCH_BS_YEAR; y < year; y++) {
    const yd = BS_DATA[y]?.reduce((a, b) => a + b, 0);
    if (yd === undefined) throw new RangeError(`bsToAd: year ${y} not in lookup table`);
    totalDays += yd;
  }

  // Add complete months in the target year
  for (let m = 1; m < month; m++) {
    totalDays += BS_DATA[year][m - 1];
  }

  // Add days within the month (day is 1-based)
  totalDays += day - 1;

  const result = new Date(EPOCH_AD);
  result.setDate(result.getDate() + totalDays);
  return result;
}

/**
 * Returns the number of days in a BS month.
 */
export function daysInBsMonth(year: number, month: number): number {
  return BS_DATA[year]?.[month - 1] ?? 30;
}
